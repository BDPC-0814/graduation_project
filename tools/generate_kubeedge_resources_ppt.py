    OUT.parent.mkdir(parents=True, exist_ok=True)
    target = OUT
    try:
        handle = zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED)
    except PermissionError:
        target = FALLBACK_OUT
        handle = zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED)

